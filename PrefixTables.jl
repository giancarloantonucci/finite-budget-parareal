# PrefixTables.jl
#
# tab:prefix_summary (supplement), from the records of PrefixRuns.jl: for each case
# and acceptance, the fine batches, how the run stopped, and the lengths of the
# exact and accurate prefixes.
#
# Needs Serialization and StaticArrays.
# Run:     julia PrefixTables.jl
# Writes:  Tables/prefix_summary.tex

using Serialization, StaticArrays  # the archived record holds SVectors

records = deserialize(joinpath(@__DIR__, "Records", "prefix_accuracy.jls"))  # only load records you made yourself

cases = [("RK4 scaling", "RK4 coarse solver, prescribed start"),
         ("Euler prescribed", "Explicit Euler coarse solver, prescribed start"),
         ("Euler control", "Explicit Euler coarse solver, replicate start")]
rules = ("standard", "psi_lyap", "psi_lip", "coarse")
rule_label = Dict("coarse" => "coarse-only", "standard" => "standard",
                  "psi_lyap" => raw"$\psi$ ($w=e^{\lambda\Delta T}$)", "psi_lip" => raw"$\psi$ (secant $w$)")
stop = Dict("converged" => "C", "exact" => "E", "budget_exhausted" => "B", "nonfinite" => "F", "coarse" => "",
            "criterion" => "C", "exact_prefix" => "E")  # the last two: names in older records
math(x) = "\$$x\$"

# The largest n with ‖U_m - U_m*‖ ≤ η for every m ≤ n; errors[1] belongs to U_0.
prefix(errors, η) = something(findfirst(e -> !(e <= η), errors), length(errors) + 1) - 2

function row(r)
    lengths = r.status == "nonfinite" ? fill("--", 3) : [math(prefix(r.errors, η)) for η in (0.0, 1e-3, 1.0)]
    batches = r.rule == "coarse" ? "" : math(r.fine_batches)  # blank: does not apply
    return join([rule_label[r.rule], batches, stop[r.status], lengths...], " & ")
end
# Each case's rows under its own heading row; a page may break before a heading, not after it.
body = join(map(cases) do (name, heading)
    rs = [only(r for r in records if r.case == name && r.rule == rule) for rule in rules]
    return "\\multicolumn{6}{c}{\\textit{$heading}}\\\\*\n" * join(row.(rs), "\\\\*\n") * "\\\\\n"
end, "\\midrule\n")

head = raw"& \multicolumn{2}{c}{Stopping} & \multicolumn{3}{c}{Prefix length}" * "\\\\\n" *
       raw"\cmidrule(lr){2-3}\cmidrule(lr){4-6}" * "\n" *
       raw"Rule & $K_F$ & Stop & $n_0$ & $n_{10^{-3}}$ & $n_1$" * "\\\\\n"
caption = raw"Prefix lengths for Lorenz-63 at $N = 128$ and $H = 0.01$: $n_\eta$ is the largest $n$ such that $\|U_m-U_m^*\|\le\eta$ for every $0\le m\le n$, so $n_0$ counts the exactly reproduced interfaces. The prescribed start is $(2,3,-14)$; the replicate start is the first prepared $N=128$ start of the control with a poor coarse solver. A failed run (F) accepts no interfaces."

mkpath(joinpath(@__DIR__, "Tables"))
write(joinpath(@__DIR__, "Tables", "prefix_summary.tex"),
      "% Generated by PrefixTables.jl.\n" *
      raw"\Needspace{20\baselineskip}\begingroup\small\setlength{\tabcolsep}{10pt}\renewcommand{\arraystretch}{1.15}" * "\n" *  # its own width, centred
      raw"\begin{longtable}{@{}cccccc@{}}" * "\n" *
      "\\caption{\\rev{$caption}}\\label{tab:prefix_summary}\\\\\n" *
      "\\toprule\n" * head * "\\midrule\\endfirsthead\n" *
      "\\multicolumn{6}{l}{\\tablename~\\thetable\\ (continued)}\\\\\n" *
      "\\toprule\n" * head * "\\midrule\\endhead\n" *
      "\\multicolumn{6}{r}{Continued on next page}\\\\\\endfoot\n" *
      "\\bottomrule\\endlastfoot\n" * body * "\\end{longtable}\\endgroup\n")
