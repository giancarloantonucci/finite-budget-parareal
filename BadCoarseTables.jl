# BadCoarseTables.jl
#
# Tables of the poor-coarse control, from the records of BadCoarseRuns.jl.
#   Article:    tab:bad_coarse (H = 0.01).
#   Supplement: tab:bad_coarse_full (H = 0.01 and 0.02).
# Outcomes count every replicate, failures included; K_F and distances use only the
# runs that accepted, and distances are means over them. Intervals are bootstrap 95%
# intervals for the mean paired difference from the coarse-only distance, resampling
# whole replicates. A blank cell does not apply; "--" is a value lost to failure.
#
# Needs Printf, Random, Serialization and Statistics.
# Run:     julia BadCoarseTables.jl
# Writes:  Tables/bad_coarse_compact.tex, Tables/bad_coarse_full.tex

using Printf, Random, Serialization, Statistics

records = deserialize(joinpath(@__DIR__, "Records", "bad_coarse.jls"))  # only load records you made yourself

# Three significant figures. A column whose entries include one below 0.01 writes its
# entries below 1 as m × 10^e; every other entry is a plain decimal. `num(x, scientific(xs))`
# formats an entry of the column xs; a lone value goes by its own size.
scientific(xs) = any(x -> isfinite(x) && 0 < abs(x) < 0.01, xs)
function decimal(x)
    iszero(x) && return raw"$0$"
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    return "\$" * Printf.format(Printf.Format("%.$(max(0, 2 - e))f"), parse(Float64, mantissa) * 10.0^e) * "\$"
end
function num(x, sci = false)
    isfinite(x) || return "--"
    iszero(x) && return raw"$0$"
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    e < -2 || (sci && e < 0) || return decimal(x)
    return "\$$mantissa\\times 10^{$e}\$"
end
# An interval, each end to three significant figures in plain decimals.
bracket((lo, hi)) = isfinite(lo) && isfinite(hi) ? "[$(decimal(lo)), $(decimal(hi))]" : "--"
math(x) = "\$$x\$"
multirow(n, x) = "\\multirow{$n}{*}{$x}"

Hs, Ns = Tuple(sort(unique(r.H for r in records))), Tuple(sort(unique(r.N for r in records)))
rules = ("psi_lyap", "psi_lip")
rule_label = Dict("coarse" => "coarse-only", "psi_lyap" => raw"$\psi$ ($w=e^{\lambda\Delta T}$)",
                  "psi_lip" => raw"$\psi$ (secant $w$)")
code = Dict("converged" => "C", "exact" => "E", "budget_exhausted" => "B", "nonfinite" => "F",
            "criterion" => "C", "exact_prefix" => "E")  # the last two: names in older records

replicates(H, N, rule) = sort([r for r in records if r.H == H && r.N == N && r.criterion == rule]; by = r -> r.rep)
accepted(rs) = filter(r -> isfinite(r.w1), rs)

# How the replicates ended, e.g. "1C, 7E".
function outcomes(rs)
    codes = [code[r.status] for r in rs]
    return join(("$(count(==(c), codes))$c" for c in ("C", "E", "B", "F") if c in codes), ", ")
end
function batches(rs)
    isempty(rs) && return "--"
    low, high = extrema(r.fine_batches for r in rs)
    return low == high ? math(low) : "\$$low\$--\$$high\$"
end
mean_of(rs, field) = isempty(rs) ? NaN : mean(getproperty(r, field) for r in rs)  # NaN prints as "--"
average(rs, field, sci = false) = num(mean_of(rs, field), sci)

function interval(differences; seed = 2718, B = 2000)
    rng = MersenneTwister(seed)
    n = length(differences)
    means = [mean(differences[rand(rng, 1:n, n)]) for _ in 1:B]
    return bracket(quantile(means, [0.025, 0.975]))
end
function versus_coarse(H, N, rule)
    rs = accepted(replicates(H, N, rule))
    isempty(rs) && return "--"
    coarse = Dict(r.rep => r for r in replicates(H, N, "coarse"))
    return interval([r.w1 - coarse[r.rep].w1 for r in rs])
end

tables = joinpath(@__DIR__, "Tables")
mkpath(tables)
# Tables whose floats and captions are in the paper. Wide ones fill the text width
# with tight spacing; narrow ones (`natural`) keep their own width, with 10pt either
# side of each column.
function float_table(name, ncols, head, body; natural = false)
    spec = (natural ? "@{}" : raw"@{\extracolsep{\fill}}") * "c"^ncols * "@{}"
    opening, closing = natural ? ("\\begin{tabular}", "\\end{tabular}") : ("\\begin{tabular*}{\\textwidth}", "\\end{tabular*}")
    write(joinpath(tables, name * ".tex"),
          "% Generated by BadCoarseTables.jl.\n" *
          "\\setlength{\\tabcolsep}{$(natural ? 10 : 1.5)pt}\\renewcommand{\\arraystretch}{1.15}\n" *
          opening * "{$spec}\\toprule\n" * head * "\\midrule\n" * body * "\\bottomrule" * closing * "\n")
end

# Article: H = 0.01, the two rules against both baselines.
article_H = 0.01
compact_coarse(N) = replicates(article_H, N, "coarse")
compact_sci = (base = scientific([mean_of(compact_coarse(N), :basew1) for N in Ns]),
               coarse = scientific([mean_of(compact_coarse(N), :w1) for N in Ns]),
               accepted = scientific([mean_of(accepted(replicates(article_H, N, rule)), :w1) for N in Ns for rule in rules]))
compact = join(map(Ns) do N
    cs = replicates(article_H, N, "coarse")
    lines = map(enumerate(rules)) do (k, rule)
        rs = replicates(article_H, N, rule)
        cells = [k == 1 ? multirow(2, math(N)) : "", rule_label[rule], outcomes(rs), batches(accepted(rs)),
                 k == 1 ? multirow(2, average(cs, :basew1, compact_sci.base)) : "",
                 k == 1 ? multirow(2, average(cs, :w1, compact_sci.coarse)) : "",
                 average(accepted(rs), :w1, compact_sci.accepted), versus_coarse(article_H, N, rule)]
        return join(cells, " & ") * (k == 1 ? "\\\\*\n" : "\\\\\n")
    end
    return join(lines)
end, "\\addlinespace[3pt]\n")
float_table("bad_coarse_compact", 8,
            raw"& & & & \multicolumn{3}{c}{$\overline{W}_1$ to the fine reference} & 95\% paired CI" * "\\\\\n" *
            raw"\cmidrule(lr){5-7}\cmidrule(lr){8-8}" * "\n" *
            raw"$N$ & Rule & Outcomes & $K_F$ & Fine baseline & Coarse-only & Accepted & vs coarse-only" * "\\\\\n",
            compact)

# Supplement: both coarse steps, every trajectory, with one distance column.
full_sci = scientific([v for H in Hs for N in Ns
                       for v in [mean_of(replicates(H, N, "coarse"), :basew1); mean_of(accepted(replicates(H, N, "coarse")), :w1);
                                 [mean_of(accepted(replicates(H, N, rule)), :w1) for rule in rules]]])
function full(H)
    groups = map(enumerate(Ns)) do (j, N)
        cs = replicates(H, N, "coarse")
        step = j == 1 ? multirow(4length(Ns), math(H)) : ""
        lines = [join([step, multirow(4, math(N)), "fine baseline", "", "", average(cs, :basew1, full_sci), ""], " & ") * "\\\\*\n",
                 join(["", "", "coarse-only", "", "", average(accepted(cs), :w1, full_sci), ""], " & ") * "\\\\*\n"]
        for rule in rules
            rs = replicates(H, N, rule)
            cells = ["", "", rule_label[rule], outcomes(rs), batches(accepted(rs)), average(accepted(rs), :w1, full_sci),
                     versus_coarse(H, N, rule)]
            push!(lines, join(cells, " & ") * (rule != last(rules) ? "\\\\*\n" : "\\\\\n"))
        end
        return join(lines)
    end
    return join(groups, "\\addlinespace[3pt]\n")
end
float_table("bad_coarse_full", 7,
            raw"& & & & & & 95\% paired CI" * "\\\\\n" * raw"\cmidrule(lr){7-7}" * "\n" *
            raw"$H$ & $N$ & Trajectory & Outcomes & $K_F$ & $\overline{W}_1$ & vs coarse-only" * "\\\\\n",
            join(full.(Hs), "\\midrule\n"); natural = true)
