# LongChunkTables.jl
#
# Tables of the long-chunk grids (sec:submitted_grid), from Records/submitted_grid.jls
# (LongChunkRuns.jl).
#   Supplement: tab:submitted_grid_summary and tab:submitted_grid_endpoint.
#   Printed:    the numbers the text quotes: stops over all runs, and on the T = 500 grid
#               the secant runs that reach exact completion and the longest secant
#               acceptances after one or two corrections.
# The families are the growing horizon (N = 100), strong scaling (T = 500) and weak
# scaling (T = 5N); the common endpoint N = 100, T = 500 belongs to all three.
#
# Needs Printf and Serialization.
# Run:     julia LongChunkTables.jl
# Writes:  Tables/submitted_grid_summary.tex, submitted_grid_endpoint.tex

using Printf, Serialization

records = deserialize(joinpath(@__DIR__, "Records", "submitted_grid.jls"))  # only load records you made yourself
length(unique((r.xi, r.N, r.T, r.criterion) for r in records)) == length(records) || error("duplicate records")
# Columns the tables leave out, with the caption saying why.
all(r -> r.fine_batches == r.sweeps + 1, records) || error("K_F ≠ s + 1 somewhere; the tables need an s column")
all(r -> r.status in ("criterion", "exact_prefix"), records) ||
    error("a run exhausted its budget or failed; the summary needs B and F columns")

rule_order = ("standard", "psi_lyap", "psi_lip")
rule_label = Dict("standard" => "standard", "psi_lyap" => raw"$\psi$ ($w=e^{\lambda\Delta T}$)",
                  "psi_lip" => raw"$\psi$ (secant $w$)")
families = (("Growing horizon: \$N=100\$", r -> r.N == 100),
            ("Strong scaling: \$T=500\$", r -> r.T == 500),
            ("Weak scaling: \$T=5N\$", r -> r.T == 5 * r.N))

# Three significant figures. A column whose entries include one below 0.01 writes its
# entries below 1 as m × 10^e; every other entry is a plain decimal. Text passes through.
function scientific(x)
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    return "\$$mantissa\\times 10^{$e}\$"
end
function decimal(x)
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    return "\$" * Printf.format(Printf.Format("%.$(max(0, 2 - e))f"), parse(Float64, mantissa) * 10.0^e) * "\$"
end
function column(xs)
    scientific_column = any(x -> x isa AbstractFloat && 0 < abs(x) < 0.01, xs)
    return map(xs) do x
        x isa AbstractString && return x
        x isa Integer && return "\$$x\$"
        iszero(x) && return raw"$0$"
        return scientific_column && abs(x) < 1 ? scientific(x) : decimal(x)
    end
end
span(xs) = minimum(xs) == maximum(xs) ? "\$$(minimum(xs))\$" : "\$$(minimum(xs))\$--\$$(maximum(xs))\$"
row(cells) = join(cells, " & ")
heading(ncols, text) = "\\multicolumn{$ncols}{c}{\\textit{$text}}\\\\*\n"
# The rows of one ξ, with ξ written once beside them.
block(ξ, lines) = join(((i == 1 ? "\\multirow{$(length(lines))}{*}{\$$(ξ)\$} & " : " & ") * line
                        for (i, line) in enumerate(lines)), "\\\\*\n") * "\\\\\n"

tables = joinpath(@__DIR__, "Tables")
mkpath(tables)
# A supplement table that may run over pages, at its natural width; the heading repeats
# and the page foot carries no rule of its own.
function supplement_table(name, caption, ncols, head, body)
    write(joinpath(tables, name * ".tex"),
          "% Generated by LongChunkTables.jl.\n" *
          "\\Needspace{20\\baselineskip}\\begingroup\\small\\setlength{\\tabcolsep}{10pt}\\renewcommand{\\arraystretch}{1.15}\n" *
          "\\begin{longtable}{@{}" * "c"^ncols * "@{}}\n" *
          "\\caption{\\rev{$caption}}\\label{tab:$name}\\\\\n" *
          "\\toprule\n" * head * "\\midrule\\endfirsthead\n" *
          "\\multicolumn{$ncols}{l}{\\tablename~\\thetable\\ (continued)}\\\\\n" *
          "\\toprule\n" * head * "\\midrule\\endhead\n" *
          "\\multicolumn{$ncols}{r}{Continued on next page}\\\\\\endfoot\n" *
          "\\bottomrule\\endlastfoot\n" * body * "\\end{longtable}\\endgroup\n")
end

runs(ξ, rule, in_family) = filter(r -> r.xi == ξ && r.criterion == rule && in_family(r), records)
summary_rows = [(family, ξ, rule) for (family, _) in families for ξ in (10, 100) for rule in rule_order]
family_of = Dict(families)
largest_error = column([maximum(r.error for r in runs(ξ, rule, family_of[family])) for (family, ξ, rule) in summary_rows])
summary_cells = Dict(key => [rule_label[key[3]], span([r.fine_batches for r in runs(key[2], key[3], family_of[key[1]])]),
                             ("\$$(count(r -> r.status == s, runs(key[2], key[3], family_of[key[1]])))\$"
                              for s in ("criterion", "exact_prefix"))..., largest_error[i]]
                     for (i, key) in enumerate(summary_rows))
supplement_table("submitted_grid_summary",
                 raw"Long-chunk grids: family summaries. Each run uses $K_F=s+1$ fine batches; C and E count stops by the criterion and by exact completion, and no run exhausts its budget or fails. The last column is the largest interface error over the family's runs. The common endpoint is included in each family summary but only once in the 900 distinct runs; row totals across families therefore exceed 900.",
                 6, raw"& & & \multicolumn{2}{c}{Stops} & \\\cmidrule(lr){4-5}" * "\n" *
                    raw"$\xi$ & Rule & $K_F$ & C & E & $\max\|e\|_2$" * "\\\\\n",
                 join((heading(6, family) *
                       join((block(ξ, [row(summary_cells[(family, ξ, rule)]) for rule in rule_order]) for ξ in (10, 100)),
                            "\\addlinespace[3pt]\n")
                       for (family, _) in families), "\\midrule\n"))

endpoint(ξ, rule) = only(r for r in records if r.xi == ξ && r.N == 100 && r.T == 500 && r.criterion == rule)
all(endpoint(ξ, rule).status == "criterion" for ξ in (10, 100) for rule in rule_order) ||
    error("an endpoint run did not stop by its criterion; the caption says all do")
# Equal fine batches mean the two weighted rules accept the same iterate; they then share one row.
shared(ξ) = endpoint(ξ, "psi_lyap").fine_batches == endpoint(ξ, "psi_lip").fine_batches
shown = [(ξ, rule) for ξ in (10, 100) for rule in rule_order if !(shared(ξ) && rule == "psi_lip")]
shown_label(ξ, rule) = shared(ξ) && rule == "psi_lyap" ? raw"$\psi$ (either $w$)" : rule_label[rule]
endpoint_errors, endpoint_speedups = column([endpoint(k...).error for k in shown]), column([endpoint(k...).speedup for k in shown])
endpoint_cells = [[shown_label(k...), "\$$(endpoint(k...).fine_batches)\$", endpoint_errors[i], endpoint_speedups[i]]
                  for (i, k) in enumerate(shown)]
shared_text = join(("\$\\xi=$(ξ)\$" for ξ in (10, 100) if shared(ξ)), " and ")
supplement_table("submitted_grid_endpoint",
                 raw"Common endpoint $N=100$, $T=500$. All six runs stop by their criterion. $\mathcal S=N/(K_F+\zeta K_G)$ is the modelled speed-up, with $\zeta$ the coarse-to-fine step ratio per chunk. " *
                 (isempty(shared_text) ? "" : "At $shared_text both weighted rules take the same fine batches, so they accept the same iterate and share one row. ") *
                 raw"At $\xi=10$ the Lyapunov rule accepts the coarse interfaces with no correction: this is vacuous acceptance relative to pointwise accuracy, not a successful correction of the tail.",
                 5, raw"$\xi$ & Rule & $K_F$ & $\|e\|_2$ & $\mathcal S$" * "\\\\\n",
                 join((block(ξ, [row(c) for (k, c) in zip(shown, endpoint_cells) if k[1] == ξ]) for ξ in (10, 100)),
                      "\\addlinespace[3pt]\n"))

# The numbers the text quotes.
println("All runs: ", count(r -> r.status == "exact_prefix", records), " E, ", count(r -> r.status == "criterion", records),
        " C, of ", length(records))
for ξ in (10, 100)
    secant = filter(r -> r.xi == ξ && r.T == 500 && r.criterion == "psi_lip", records)
    exact = sort([r.N for r in secant if r.status == "exact_prefix"])
    early = minimum(r.N for r in secant if r.status == "criterion" && r.sweeps in (1, 2))
    @printf("T = 500, ξ = %d: %d secant runs exact (N = %s), shortest chunk 500/%d = %.3g; longest acceptance after 1-2 corrections 500/%d = %.4g\n",
            ξ, length(exact), join(exact, ", "), maximum(exact), 500 / maximum(exact), early, 500 / early)
end
