# StatisticalTables.jl
#
# Tables of the replicated statistical comparisons, from the records of
# StatisticalRuns.jl, in paper order.
#   Article:    tab:w1_baseline (N = 16, 32, 128).
#   Supplement: tab:statistics_full, tab:observables_full and tab:sensitivity_summary.
# Entries are means over the replicates. Intervals are bootstrap 95% intervals for
# the mean of the paired replicate differences, resampling whole replicates.
#
# Needs Printf, Random, Serialization and Statistics.
# Run:     julia StatisticalTables.jl
# Writes:  Tables/statistics_compact.tex, Tables/statistics_full.tex,
#          Tables/observables_full.tex, Tables/sensitivity_summary.tex

using Printf, Random, Serialization, Statistics

records = deserialize(joinpath(@__DIR__, "Records", "statistics.jls"))  # only load records you made yourself
sensitivity = deserialize(joinpath(@__DIR__, "Records", "sensitivity.jls"))

# Three significant figures. A column whose entries include one below 0.01 writes its
# entries below 1 as m × 10^e; every other entry is a plain decimal. `num(x, scientific(xs))`
# formats an entry of the column xs; a lone value goes by its own size.
scientific(xs) = any(x -> isfinite(x) && 0 < abs(x) < 0.01, xs)
function decimal(x)
    iszero(x) && return raw"$0$"
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    return "\$" * Printf.format(Printf.Format("%.$(max(0, 2 - e))f"), parse(Float64, mantissa) * 10.0^e) * "\$"
end
function num(x, sci = false)
    isfinite(x) || return "--"
    iszero(x) && return raw"$0$"
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    e < -2 || (sci && e < 0) || return decimal(x)
    return "\$$mantissa\\times 10^{$e}\$"
end
# An interval, each end to three significant figures in plain decimals.
bracket((lo, hi)) = isfinite(lo) && isfinite(hi) ? "[$(decimal(lo)), $(decimal(hi))]" : "--"
math(x) = "\$$x\$"
multirow(n, x) = "\\multirow{$n}{*}{$x}"

problems, rules = ("lorenz", "lorenz96"), ("coarse", "psi_lyap", "psi_lip")
problem_label = Dict("lorenz" => "Lorenz-63", "lorenz96" => "Lorenz-96")
rule_label = Dict("coarse" => "coarse-only", "psi_lyap" => raw"$\psi$ ($w=e^{\lambda\Delta T}$)",
                  "psi_lip" => raw"$\psi$ (secant $w$)")
Ns = Tuple(sort(unique(r.N for r in records)))

tables = joinpath(@__DIR__, "Tables")
mkpath(tables)
write_tex(name, text) = write(joinpath(tables, name * ".tex"), "% Generated by StatisticalTables.jl.\n" * text)
# k centred columns. Wide tables fill the text width with tight spacing; narrow
# ones (`natural`) keep their own width, with 10pt either side of each column.
columns(k, natural) = (natural ? "@{}" : raw"@{\extracolsep{\fill}}") * "c"^k * "@{}"
spacing(colsep) = "\\setlength{\\tabcolsep}{$(colsep)pt}\\renewcommand{\\arraystretch}{1.15}"

# A table whose float and caption are in the paper.
function float_table(name, ncols, head, body; natural = false)
    opening, closing = natural ? ("\\begin{tabular}", "\\end{tabular}") : ("\\begin{tabular*}{\\textwidth}", "\\end{tabular*}")
    write_tex(name, spacing(natural ? 10 : 1.5) * "\n" * opening * "{$(columns(ncols, natural))}\\toprule\n" *
                    head * "\\midrule\n" * body * "\\bottomrule" * closing * "\n")
end

# A supplement table that may run over pages. It starts only where its heading and
# first rows fit; the heading repeats; rows end in \\* inside a group, so breaks fall
# only between groups; and the page foot carries no rule of its own. A panel has a
# bold title above its rules, and only the first panel of a table has the caption.
# longtable steps the table counter even without a caption, so an uncaptioned panel steps
# it back and keeps its table's number, with its own hyperref anchor.
same_number = "\\addtocounter{table}{-1}\\def\\theHtable{\\arabic{table}.\\number\\value{LT@tables}}"
function longtable(ncols, head, body; caption = "", title = "", colsep = 1.5, natural = false)
    width = natural ? "" : "\\setlength{\\LTleft}{0pt}\\setlength{\\LTright}{0pt}"  # else centred at its own width
    return "\\Needspace{20\\baselineskip}\\begingroup\\small" * spacing(natural ? 10 : colsep) * width * "\n" *
           (isempty(caption) ? same_number : "") * "\\begin{longtable}{$(columns(ncols, natural))}\n" * caption *
           (isempty(title) ? "" : "\\multicolumn{$ncols}{@{}l}{\\textbf{$title}}\\\\\n") *
           "\\toprule\n" * head * "\\midrule\\endfirsthead\n" *
           "\\multicolumn{$ncols}{l}{\\tablename~\\thetable\\ (continued)}\\\\\n" *
           "\\toprule\n" * head * "\\midrule\\endhead\n" *
           "\\multicolumn{$ncols}{r}{Continued on next page}\\\\\\endfoot\n" *
           "\\bottomrule\\endlastfoot\n" * body * "\\end{longtable}\\endgroup\n"
end
caption_line(name, caption) = "\\caption{\\rev{$caption}}\\label{tab:$name}\\\\\n"
supplement_table(name, caption, ncols, head, body; options...) =
    write_tex(name, longtable(ncols, head, body; caption = caption_line(name, caption), options...))

# Each problem's rows under its own heading row; a page may break before a heading, not after it.
function by_problem(rows, ncols)
    return join(("\\multicolumn{$ncols}{c}{\\textit{$(problem_label[name])}}\\\\*\n" * rows(name)
                 for name in problems), "\\midrule\n")
end

by_N(group, Ns) = join((group(N) for N in Ns), "\\addlinespace[3pt]\n")

# A rule's records at one problem and N, in replicate order, checked against the
# coarse-only ones they are paired with: same replicates, same baseline.
function replicates(name, N, rule)
    rs = sort([r for r in records if r.problem == name && r.N == N && r.criterion == rule]; by = r -> r.rep)
    cs = sort([r for r in records if r.problem == name && r.N == N && r.criterion == "coarse"]; by = r -> r.rep)
    [r.rep for r in rs] == [c.rep for c in cs] && all(r.basew1 == c.basew1 for (r, c) in zip(rs, cs)) ||
        error("$name, N = $N: the $rule records do not pair with the coarse-only ones")
    return rs
end
mean_of(rs, field) = mean(getproperty(r, field) for r in rs)
average(rs, field, sci = false) = num(mean_of(rs, field), sci)

function interval(differences; seed = 2718, B = 2000)
    rng = MersenneTwister(seed)
    n = length(differences)
    means = [mean(differences[rand(rng, 1:n, n)]) for _ in 1:B]
    return bracket(quantile(means, [0.025, 0.975]))
end
versus_coarse(name, N, rule) =
    interval([r.w1 - c.w1 for (r, c) in zip(replicates(name, N, rule), replicates(name, N, "coarse"))])
versus_baseline(name, N, rule) = interval([r.w1 - r.basew1 for r in replicates(name, N, rule)])

# Article: the two rules against both baselines at three horizons.
article_Ns = (16, 32, 128)
issubset(article_Ns, Ns) || error("article_Ns $article_Ns is not in the grid $Ns")
coarse_of(name, N) = replicates(name, N, "coarse")
compact_sci = (base = scientific([mean_of(coarse_of(name, N), :basew1) for name in problems for N in article_Ns]),
               coarse = scientific([mean_of(coarse_of(name, N), :w1) for name in problems for N in article_Ns]),
               accepted = scientific([mean_of(replicates(name, N, rule), :w1)
                                      for name in problems for N in article_Ns for rule in ("psi_lyap", "psi_lip")]))
compact(name) = by_N(article_Ns) do N
    cs = replicates(name, N, "coarse")
    lines = map(enumerate(("psi_lyap", "psi_lip"))) do (k, rule)
        cells = [k == 1 ? multirow(2, math(N)) : "", rule_label[rule],
                 k == 1 ? multirow(2, average(cs, :basew1, compact_sci.base)) : "",
                 k == 1 ? multirow(2, average(cs, :w1, compact_sci.coarse)) : "",
                 average(replicates(name, N, rule), :w1, compact_sci.accepted), versus_coarse(name, N, rule)]
        return join(cells, " & ") * (k == 1 ? "\\\\*\n" : "\\\\\n")
    end
    return join(lines)
end
float_table("statistics_compact", 6,
            raw"& & \multicolumn{3}{c}{$\overline{W}_1$ to the fine reference} & 95\% paired CI" * "\\\\\n" *
            raw"\cmidrule(lr){3-5}\cmidrule(lr){6-6}" * "\n" *
            raw"$N$ & Rule & Fine baseline & Coarse-only & Accepted & vs coarse-only" * "\\\\\n",
            by_problem(compact, 6))

# Supplement: every trajectory's distance with both paired intervals.
full_sci = scientific([[mean_of(coarse_of(name, N), :basew1) for name in problems for N in Ns];
                       [mean_of(replicates(name, N, rule), :w1) for name in problems for N in Ns for rule in rules]])
full(name) = by_N(Ns) do N
    cs = replicates(name, N, "coarse")
    lines = [join([multirow(4, math(N)), "fine baseline", average(cs, :basew1, full_sci), "", ""], " & ") * "\\\\*\n"]
    for (k, rule) in enumerate(rules)
        cells = ["", rule_label[rule], average(replicates(name, N, rule), :w1, full_sci),
                 rule == "coarse" ? "" : versus_coarse(name, N, rule), versus_baseline(name, N, rule)]
        push!(lines, join(cells, " & ") * (k < length(rules) ? "\\\\*\n" : "\\\\\n"))
    end
    return join(lines)
end
supplement_table("statistics_full",
                 raw"Marginal Wasserstein distances $\overline{W}_1$ to the reference fine trajectory, as means over eight spun-up replicate pairs. The intervals are bootstrap 95\% intervals for the mean paired difference from the coarse-only distance and from the fine-baseline distance, which share the reference fine trajectory within a replicate; negative intervals indicate a smaller distance than the named comparator.",
                 5, raw"& & & \multicolumn{2}{c}{95\% paired CI}" * "\\\\\n" * raw"\cmidrule(lr){4-5}" * "\n" *
                    raw"$N$ & Trajectory & $\overline{W}_1$ & vs coarse-only & vs fine baseline" * "\\\\\n",
                 by_problem(full, 5))

# Supplement: sliced distance, moment errors and autocorrelation error, in two panels.
observables = (:sliced, :energy_error, :mean_error, :neighbour_error, :coupled_error, :ac_error)
baselines = (:basesliced, :base_energy, :base_mean, :base_neighbour, :base_coupled, :base_ac)
# Each column holds one observable: its fine-baseline value and the trajectories' values.
observed_sci = [scientific([[mean_of(coarse_of(name, N), b) for name in problems for N in Ns];
                            [mean_of(replicates(name, N, rule), f) for name in problems for N in Ns for rule in rules]])
                for (f, b) in zip(observables, baselines)]
# The rows of one problem for the observables in `columns`.
observed(columns) = name -> by_N(Ns) do N
    cs = replicates(name, N, "coarse")
    lines = [join([multirow(4, math(N)), "fine baseline", (average(cs, baselines[j], observed_sci[j]) for j in columns)...],
                  " & ") * "\\\\*\n"]
    for (k, rule) in enumerate(rules)
        rs = replicates(name, N, rule)
        push!(lines, join(["", rule_label[rule], (average(rs, observables[j], observed_sci[j]) for j in columns)...], " & ") *
                     (k < length(rules) ? "\\\\*\n" : "\\\\\n"))
    end
    return join(lines)
end
observables_caption = raw"Distributional, moment, and temporal diagnostics against the reference fine trajectory. SW is the sliced Wasserstein distance over 16 fixed directions. The remaining columns are absolute errors in mean energy $\|u\|_2^2/d$, mean $x_1$, the mean neighbour product, mean $x_1x_3$, and first-coordinate autocorrelation (AC) at lag 0.5. The neighbour product is $x_1x_2$ for Lorenz-63 and $d^{-1}\sum_i x_ix_{i-1}$ for Lorenz-96. The fine-baseline rows use the independent fine trajectory. Entries are means over eight spun-up replicate pairs; these diagnostic means carry no uncertainty intervals."
write_tex("observables_full",
          longtable(5, raw"& & Distribution & \multicolumn{2}{c}{Moments}" * "\\\\\n" *
