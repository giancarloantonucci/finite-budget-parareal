# Supplement: the secant rule at N = 16 as the tolerance ϵ and the guard τ each vary
# from ϵ = 1e-9, τ = 1e-10.
power(x) = "\$10^{$(round(Int, log10(x)))}\$"
sweeps = [("tolerance", [(ϵ, 1e-10) for ϵ in (1e-7, 1e-9, 1e-11)]),
          ("guard", [(1e-9, τ) for τ in (1e-12, 1e-10, 1e-8)])]
setting_runs(name, ϵ, τ) = [r for r in sensitivity if r.problem == name && r.epsilon == ϵ && r.tau == τ]
sensitivity_sci = scientific([mean(r.w1 for r in setting_runs(name, ϵ, τ))
                              for name in problems for (_, settings) in sweeps for (ϵ, τ) in settings])
function sensitivity_rows(name)
    groups = map(sweeps) do (parameter, settings)
        lines = map(enumerate(settings)) do (k, (ϵ, τ))
            rs = setting_runs(name, ϵ, τ)
            low, high = extrema(r.sweeps for r in rs)
            held(x) = k == 1 ? multirow(length(settings), power(x)) : ""  # the setting this sweep holds fixed
            cells = [k == 1 ? multirow(length(settings), parameter) : "",
                     parameter == "tolerance" ? power(ϵ) : held(ϵ), parameter == "guard" ? power(τ) : held(τ),
                     low == high ? math(low) : "\$$low\$--\$$high\$", num(mean(r.w1 for r in rs), sensitivity_sci)]
            return join(cells, " & ") * (k < length(settings) ? "\\\\*\n" : "\\\\\n")
        end
        return join(lines)
    end
    return join(groups, "\\addlinespace[3pt]\n")
end
float_table("sensitivity_summary", 5,
            raw"Parameter & $\epsilon$ & $\tau_{\mathrm{sec}}$ & $s$ & $\overline{W}_1$" * "\\\\\n",
            by_problem(sensitivity_rows, 5); natural = true)

# The check behind the article's caption: where the two weighted rules' entries coincide,
# do they accept the same interfaces in every replicate?
println("Weighted rules accept identical interfaces in every replicate:")
for name in problems, N in Ns
    hashes(rule) = [r.interface_hash for r in sort(filter(r -> r.problem == name && r.N == N && r.criterion == rule, records);
                                                   by = r -> r.rep)]
    println("  ", rpad(problem_label[name], 10), " N = ", rpad(N, 4), hashes("psi_lyap") == hashes("psi_lip"))
end
