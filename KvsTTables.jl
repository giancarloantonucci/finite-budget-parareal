# KvsTTables.jl
#
# Scaling tables from the records of KvsTRuns.jl, in paper order.
#   Article:    tab:scaling_logistic_main, tab:scaling_lorenz_main and
#               tab:scaling_lorenz96_main, at N = 2, 16, 128.
#   Supplement: tab:scaling_logistic_extra, tab:scaling_lorenz_extra and
#               tab:scaling_lorenz96_extra, at N = 4, 8, 32, 64; tab:scaling_lorenz
#               (Lorenz-63 at ξ = 10), tab:scaling_short_horizon and tab:scaling_periodic.
# The logistic and periodic controls report the interface error ‖e‖₂; the chaotic
# problems report the dense mean marginal W₁ of the accepted and coarse-only
# trajectories to the serial fine one.
#
# Needs Printf and Serialization.
# Run:     julia KvsTTables.jl
# Writes:  Tables/main_scaling_{logistic,lorenz,lorenz96}.tex,
#          Tables/scaling_{logistic,lorenz,lorenz96}_extra.tex,
#          Tables/scaling_{lorenz,short_horizon,periodic}.tex

using Printf, Serialization

records = deserialize(joinpath(@__DIR__, "Records", "scaling.jls"))  # only load records you made yourself

find(name, ξ, scenario, N, rule) =
    only(r for r in records if r.problem == name && r.xi == ξ && r.scenario == scenario &&
                              r.N == N && r.criterion == rule)

# Three significant figures. A column whose entries include one below 0.01 writes its
# entries below 1 as m × 10^e; every other entry is a plain decimal. `num(x, scientific(xs))`
# formats an entry of the column xs; a lone value goes by its own size.
scientific(xs) = any(x -> isfinite(x) && 0 < abs(x) < 0.01, xs)
function decimal(x)
    iszero(x) && return raw"$0$"
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    return "\$" * Printf.format(Printf.Format("%.$(max(0, 2 - e))f"), parse(Float64, mantissa) * 10.0^e) * "\$"
end
function num(x, sci = false)
    isfinite(x) || return "--"
    iszero(x) && return raw"$0$"
    mantissa, exponent = split(@sprintf("%.2e", x), 'e')
    e = parse(Int, exponent)
    e < -2 || (sci && e < 0) || return decimal(x)
    return "\$$mantissa\\times 10^{$e}\$"
end
math(x) = "\$$x\$"

stop = Dict("converged" => "C", "exact" => "E", "budget_exhausted" => "B", "nonfinite" => "F",
            "criterion" => "C", "exact_prefix" => "E")  # the last two: names in older records
rules = ("standard", "psi_w1", "psi_lyap", "psi_lip")
rule_label = Dict("standard" => "standard", "psi_w1" => raw"$\psi$ ($w=1$)",
                  "psi_lyap" => raw"$\psi$ ($w=e^{\lambda\Delta T}$)", "psi_lip" => raw"$\psi$ (secant $w$)")
problem_label = Dict("lorenz" => "Lorenz-63", "lorenz96" => "Lorenz-96")
multirow(n, x) = "\\multirow{$n}{*}{$x}"

tables = joinpath(@__DIR__, "Tables")
mkpath(tables)
write_tex(name, text) = write(joinpath(tables, name * ".tex"), "% Generated by KvsTTables.jl.\n" * text)
# k centred columns across the text width, with a fixed gap after column `split_at`
# between the strong- and weak-scaling halves; a `natural` table keeps its own width.
centred(k, split_at = nothing; natural = false) = natural ? "@{}" * "c"^k * "@{}" : raw"@{\extracolsep{\fill}}" *
    (split_at === nothing ? "c"^k : "c"^split_at * raw"@{\hspace{8pt}}" * "c"^(k - split_at)) * "@{}"
spacing = raw"\setlength{\tabcolsep}{1.5pt}\renewcommand{\arraystretch}{1.15}"

# Column labels under the strong- and weak-scaling group headings.
function header(labels, strong, weak)
    a = length(labels) + 1
    b = a + length(strong)
    return "& "^length(labels) * "\\multicolumn{$(length(strong))}{c}{Strong scaling (\$T=128\$)} & " *
           "\\multicolumn{$(length(weak))}{c}{Weak scaling (\$\\Delta T=1\$)}\\\\\n" *
           "\\cmidrule(lr){$a-$(b - 1)}\\cmidrule(lr){$b-$(b + length(weak) - 1)}\n" *
           join([labels; strong; weak], " & ") * "\\\\\n"
end

# An article table; its float and caption are in ex_article.tex.
article_table(name, ncols, split_at, head, body) =
    write_tex(name, spacing * "\n\\begin{tabular*}{\\textwidth}{$(centred(ncols, split_at))}\\toprule\n" *
                    head * "\\midrule\n" * body * "\\bottomrule\\end{tabular*}\n")

# A supplement table that may run over pages. The heading repeats; rows end in \\*
# inside a group, so breaks fall only after a group's closing rule or space, and
# the page foot carries no rule of its own.
# A narrow table (`natural`) keeps its own width, centred, with 10pt either side of each column.
function supplement_table(name, caption, ncols, head, body; split_at = nothing, natural = false)
    layout = natural ? "\\setlength{\\tabcolsep}{10pt}\\renewcommand{\\arraystretch}{1.15}" :
             spacing * "\\setlength{\\LTleft}{0pt}\\setlength{\\LTright}{0pt}"
    write_tex(name, "\\Needspace{20\\baselineskip}\\begingroup\\small" * layout * "\n" *
                    "\\begin{longtable}{$(centred(ncols, split_at; natural))}\n" *
                    "\\caption{\\rev{$caption}}\\label{tab:$name}\\\\\n" *
                    "\\toprule\n" * head * "\\midrule\\endfirsthead\n" *
                    "\\multicolumn{$ncols}{l}{\\tablename~\\thetable\\ (continued)}\\\\\n" *
                    "\\toprule\n" * head * "\\midrule\\endhead\n" *
                    "\\multicolumn{$ncols}{r}{Continued on next page}\\\\\\endfoot\n" *
                    "\\bottomrule\\endlastfoot\n" * body * "\\end{longtable}\\endgroup\n")
end

# Logistic and periodic rows: one group per ξ and rule, one row per N. In an
# article table ξ labels its whole block; across pages it labels every group.
function control_rows(name, ξs, rules, Ns, half; long)
    io = IOBuffer()
    groups = [(ξ, rule) for ξ in ξs for rule in rules]
    # Notation per column: each scenario's speed-up and error columns over this table's rows.
    shown(scenario) = [find(name, ξ, scenario, N, rule) for (ξ, rule) in groups for N in Ns]
    sci = Dict(scenario => (speedup = scientific([r.speedup for r in shown(scenario)]),
                            error = scientific([r.error for r in shown(scenario)])) for scenario in ("strong", "weak"))
    ncols = 3 + 2length(half(find(name, ξs[1], "weak", Ns[1], rules[1]), sci["weak"]))
    for (g, (ξ, rule)) in enumerate(groups)
        for (j, N) in enumerate(Ns)
            ξcell = j > 1 ? "" : long ? multirow(length(Ns), math(ξ)) :
                    rule == first(rules) ? multirow(length(rules) * length(Ns), math(ξ)) : ""
            cells = [ξcell, j == 1 ? multirow(length(Ns), rule_label[rule]) : "", math(N),
                     half(find(name, ξ, "strong", N, rule), sci["strong"])...,
                     half(find(name, ξ, "weak", N, rule), sci["weak"])...]
            println(io, join(cells, " & "), long ? "\\\\*" : "\\\\")
        end
        g == length(groups) && break
        if long || last(groups[g + 1]) == first(rules)
            println(io, "\\midrule")
        else
            println(io, "\\cmidrule(lr){2-$ncols}")
        end
    end
    return String(take!(io))
end
control_half(r, sci) = [math(r.fine_batches), stop[r.status], num(r.speedup, sci.speedup), num(r.error, sci.error)]
control_header(columns) = header([raw"$\xi$", "Rule", raw"$N$"], columns, columns)

# Chaotic rows: one group per N, one row per rule, then the coarse-only distance
# (the same for every rule) to compare with the accepted ones above it.
function chaotic_rows(name, ξ, Ns)
    io = IOBuffer()
    # Notation per column: each scenario's speed-up and distance columns, coarse-only rows included.
    shown(scenario) = [find(name, ξ, scenario, N, rule) for N in Ns for rule in rules]
    sci = Dict(scenario => (speedup = scientific([r.speedup for r in shown(scenario)]),
                            w1 = scientific([[r.w1_dense for r in shown(scenario)]; [r.coarse_w1_dense for r in shown(scenario)]]))
               for scenario in ("strong", "weak"))
    ss, sw = sci["strong"], sci["weak"]
    for (j, N) in enumerate(Ns)
        for (k, rule) in enumerate(rules)
            s, w = find(name, ξ, "strong", N, rule), find(name, ξ, "weak", N, rule)
            cells = [k == 1 ? multirow(length(rules) + 1, math(N)) : "", rule_label[rule],
                     math(s.fine_batches), stop[s.status], num(s.speedup, ss.speedup), num(s.w1_dense, ss.w1),
                     math(w.fine_batches), stop[w.status], num(w.speedup, sw.speedup), num(w.w1_dense, sw.w1)]
            println(io, join(cells, " & "), "\\\\*")
        end
        s, w = find(name, ξ, "strong", N, first(rules)), find(name, ξ, "weak", N, first(rules))
        cells = ["", "coarse-only", "", "", "", num(s.coarse_w1_dense, ss.w1), "", "", "", num(w.coarse_w1_dense, sw.w1)]
        println(io, join(cells, " & "), "\\\\")
        j < length(Ns) && println(io, "\\addlinespace[3pt]")
    end
    return String(take!(io))
end
chaotic_columns = [raw"$K_F$", "Stop", raw"$\mathcal S$", raw"$\overline{W}_1$"]
chaotic_header = header([raw"$N$", "Rule"], chaotic_columns, chaotic_columns)

# The article shows main_Ns; the supplement takes the rest of the grid that was run,
# so together they hold every N.
all_Ns = Tuple(sort(unique(r.N for r in records if r.scenario != "growing")))
main_Ns = (2, 16, 128)
issubset(main_Ns, all_Ns) || error("main_Ns $main_Ns is not in the grid $all_Ns")
extra_Ns = Tuple(filter(∉(main_Ns), all_Ns))
same_run = raw"The scaling grids share $N=T=128$, so those strong- and weak-scaling rows are the same run."
control_columns = [raw"$K_F$", "Stop", raw"$\mathcal S$", raw"$\|e\|_2$"]

article_table("main_scaling_logistic", 11, 7, control_header(control_columns),
              control_rows("logistic", (10, 100), ("standard", "psi_w1"), main_Ns, control_half; long = false))
for name in ("lorenz", "lorenz96")
    article_table("main_scaling_$name", 10, 6, chaotic_header, chaotic_rows(name, 100, main_Ns))
end

remaining = "remaining strong- and weak-scaling rows at \$N = $(join(extra_Ns, ", "))\$. The main article " *
            "gives \$N = $(join(main_Ns, ", "))\$; together these tables retain the complete grid."
supplement_table("scaling_logistic_extra",
                 "Logistic: $remaining Both \$\\xi = 10, 100\$ and both stopping rules are retained. " *
                 "Errors are unweighted interface norms.",
                 11, control_header(control_columns),
                 control_rows("logistic", (10, 100), ("standard", "psi_w1"), extra_Ns, control_half; long = true);
                 split_at = 7)
for name in ("lorenz", "lorenz96")
    supplement_table("scaling_$(name)_extra",
                     "$(problem_label[name]): $remaining Here \$\\xi = 100\$; distances use the dense mean " *
                     "marginal Wasserstein statistic.",
                     10, chaotic_header, chaotic_rows(name, 100, extra_Ns); split_at = 6)
end
supplement_table("scaling_lorenz",
                 raw"Lorenz-63 at $\xi=10$: additional strong- and weak-scaling records; $\xi=100$ is in \Cref{tab:scaling_lorenz_main}. Dense mean marginal Wasserstein distances $\overline{W}_1$ of the accepted and coarse-only trajectories use the same serial fine reference and the single prescribed start without spin-up. Sampling and work conventions are stated in \Cref{sec:scaling}. " * same_run,
                 10, chaotic_header, chaotic_rows("lorenz", 10, all_Ns); split_at = 6)

# Short horizons: the weak-scaling runs at ξ = 100 and N ≤ 16, giving the interface
# error beside the marginal distance. K_F and the coarse-only baselines are in the
# scaling tables, so they are not repeated. Each problem's rows come under a heading
# row; a page may break before a heading, not after it.
let short = (4, 8, 16), problems = ("lorenz", "lorenz96")
    shown = [find(name, 100, "weak", N, rule) for name in problems for N in short for rule in rules]
    sci_error, sci_w1 = scientific([r.error for r in shown]), scientific([r.w1_dense for r in shown])
    group(name, N) = join(map(enumerate(rules)) do (k, rule)
        r = find(name, 100, "weak", N, rule)
        cells = [k == 1 ? multirow(length(rules), math(N)) : "", rule_label[rule], num(r.error, sci_error),
                 num(r.w1_dense, sci_w1)]
        return join(cells, " & ") * (k < length(rules) ? "\\\\*\n" : "\\\\\n")
    end)
    body = join(("\\multicolumn{4}{c}{\\textit{$(problem_label[name])}}\\\\*\n" *
                 join((group(name, N) for N in short), "\\addlinespace[3pt]\n") for name in problems), "\\midrule\n")
    supplement_table("scaling_short_horizon",
                     raw"Short-horizon runs from the weak-scaling grid: $\Delta T=1$, $\xi=100$, and the prescribed starts without spin-up; $K_F$ and the coarse-only baselines are in the article's \Cref{tab:scaling_lorenz_main,tab:scaling_lorenz96_main} and in \Cref{tab:scaling_lorenz_extra,tab:scaling_lorenz96_extra}. The unweighted interface error is $\|e\|_2=(\sum_{n=0}^{N}\|U_n-U_n^*\|_2^2)^{1/2}$, including the terminal fine output; $U^*$ is the serial fine discrete reference. Dense mean marginal Wasserstein distance $\overline{W}_1$ uses the sampling protocol in \Cref{sec:scaling}. The two measures test interface tracking and finite-time marginal agreement, respectively.",
                     4, raw"$T=N$ & Rule & $\|e\|_2$ & $\overline{W}_1$" * "\\\\\n", body; natural = true)
end

supplement_table("scaling_periodic",
                 raw"Complete strong- and weak-scaling records for the periodic Lorenz-63 control. The unweighted interface error $\|e\|_2$ measures tracking of the serial fine discrete reference; $K_F$, Stop, and $\mathcal S$ follow the conventions in \Cref{sec:scaling}. " * same_run,
                 11, control_header(control_columns),
                 control_rows("periodic", (10, 100), ("standard", "psi_w1", "psi_lip"), all_Ns, control_half;
